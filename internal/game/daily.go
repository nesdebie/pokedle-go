// Package game contains the Pokédle rules: daily target selection
// and the comparison between a guess and the target.
package game

import (
	"bufio"
	"crypto/hmac"
	"crypto/sha256"
	"encoding/binary"
	"os"
	"strings"
	"time"
)

// SecretKey is the name of the variable holding the daily-pick secret.
const SecretKey = "POKEDLE_SECRET"

// DayKey formats t as the UTC day used to seed the daily pick.
func DayKey(t time.Time) string {
	return t.UTC().Format("2006-01-02")
}

// DailyIndex deterministically picks a row index in [0, n) for the day of t.
// With a secret the pick is an HMAC-SHA256 of the day (unpredictable),
// otherwise a plain SHA-256 of the day.
func DailyIndex(n int, secret string, t time.Time) int {
	if n <= 0 {
		return 0
	}

	msg := []byte(DayKey(t))
	var sum []byte
	if secret != "" {
		m := hmac.New(sha256.New, []byte(secret))
		m.Write(msg)
		sum = m.Sum(nil)
	} else {
		h := sha256.Sum256(msg)
		sum = h[:]
	}

	v := binary.BigEndian.Uint64(sum[:8])
	return int(v % uint64(n))
}

// LoadSecret returns POKEDLE_SECRET from the environment, or from the
// given .env file (generated by `make` / scripts/genkey). Empty if absent.
func LoadSecret(envFile string) string {
	if v := os.Getenv(SecretKey); v != "" {
		return v
	}

	f, err := os.Open(envFile)
	if err != nil {
		return ""
	}
	defer f.Close()

	prefix := SecretKey + "="
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if strings.HasPrefix(line, prefix) {
			return strings.TrimPrefix(line, prefix)
		}
	}
	return ""
}
